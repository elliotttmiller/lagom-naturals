import { access, mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import { basename, extname, join, relative, resolve } from 'node:path'
import sharp from 'sharp'

const root = resolve(import.meta.dirname, '..')
const outputRoot = join(root, 'src', 'assets', 'optimized')
const modulePath = join(root, 'src', 'generated', 'responsiveImages.js')
const homeGummySourceRoot = join(root, 'archive', 'assets', 'products-originals')
const homeGummyOutputRoot = join(root, 'src', 'assets', 'products', 'home-gummies')
const homeGummySources = [
  'Berry-Melon-Bliss-Photoroom-900x900.png', 'Blue-Razz-Photoroom-Photoroom-1-900x900.png',
  'Blueberry-Yum-Yum-1-Photoroom-900x900.png', 'Blueberry-Yum-Yum-3-Photoroom-900x900.png',
  'Cherry-Bliss-Photoroom-900x900.png', 'Green-Apple-Photoroom-900x900.png',
  'Peach-Photoroom-900x900.png', 'Pink-Lemonade-Photoroom-900x900.png',
  'Push-Pop-1-Photoroom-900x900.png', 'Push-Pop-Photoroom-900x900.png',
  'Strawberry-Banana-Photoroom-900x900.png', 'Strawberry-Photoroom-900x900.png',
]

const groups = [
  { name: 'homeGummies', directory: 'src/assets/products/home-gummies', widths: [480, 900] },
  { name: 'products', directory: 'src/assets/products/enhanced', widths: [480, 960] },
  { name: 'merch', directory: 'src/assets/merch', widths: [480, 960] },
  { name: 'heroMobile', directory: 'src/assets/mobile', files: ['hero.webp', 'gummies-hero.webp', 'midnight-gummies-hero.webp', 'organic-gummies-hero.webp'], widths: [480, 800] },
  { name: 'heroDesktop', directory: 'src/assets/desktop', files: ['hero.webp', 'gummies-hero.webp', 'midnight-gummies-hero.webp', 'organic-gummies-hero.webp'], widths: [960, 1600] },
  { name: 'findUs', directory: 'src/assets/mobile', files: ['find-us-hero.png'], widths: [480, 960] },
  { name: 'store', directory: 'src/assets/store', widths: [480, 960] },
  { name: 'storeDesktop', directory: 'src/assets/desktop', files: ['storefront.webp'], widths: [960, 1600] },
  { name: 'showcaseDesktop', directory: 'src/assets/showcase', files: ['seltzer-background.png', 'seltzer-splash.png'], widths: [960, 1600] },
  { name: 'showcaseMobile', directory: 'src/assets/showcase', files: ['seltzer-background-mobile.png'], widths: [480, 800] },
  { name: 'categories', directory: 'src/assets', files: ['seltzers-thumbnail.webp', 'gummies-thumbnail.webp'], widths: [320, 640] },
]

const safeKey = file => basename(file, extname(file))
const importName = value => value.replace(/[^a-zA-Z0-9_$]/g, '_')
const moduleImports = []
const moduleGroups = []

// These explicitly selected archived PNGs are the canonical visual treatment
// for the homepage gummy line. Keep the originals in archive, and generate
// normalized WebP masters for active source consumption.
await rm(homeGummyOutputRoot, { recursive: true, force: true })
await mkdir(homeGummyOutputRoot, { recursive: true })
for (const sourceName of homeGummySources) {
  const source = join(homeGummySourceRoot, sourceName)
  const output = join(homeGummyOutputRoot, `${safeKey(sourceName)}.webp`)
  await sharp(source)
    .rotate()
    .resize(900, 900, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 }, withoutEnlargement: true })
    .toColorspace('srgb')
    .webp({ quality: 82, effort: 4, smartSubsample: true })
    .toFile(output)
}

// This directory is wholly generated by this script. Recreate it from the
// canonical sources so removed groups cannot leave deployable stale assets.
await rm(outputRoot, { recursive: true, force: true })

for (const group of groups) {
  const sourceDirectory = join(root, group.directory)
  const files = group.files ?? (await readdir(sourceDirectory)).filter(file => /\.(png|jpe?g|webp)$/i.test(file))
  const entries = []

  for (const file of files) {
    const source = join(sourceDirectory, file)
    const key = safeKey(file)
    const outputDirectory = join(outputRoot, group.name)
    await mkdir(outputDirectory, { recursive: true })
    const variants = []

    for (const width of group.widths) {
      for (const format of ['avif', 'webp']) {
        const output = join(outputDirectory, `${key}-${width}.${format}`)
        const exists = await access(output).then(() => true).catch(() => false)
        if (!exists) {
          const pipeline = sharp(source).rotate().resize({ width, withoutEnlargement: true })
          if (format === 'avif') await pipeline.avif({ quality: 58, effort: 2, chromaSubsampling: '4:4:4' }).toFile(output)
          else await pipeline.webp({ quality: 76, effort: 4, smartSubsample: true }).toFile(output)
        }
        variants.push({ width, format, output })
      }
    }

    const names = {}
    for (const variant of variants) {
      const name = importName(`${group.name}_${key}_${variant.width}_${variant.format}`)
      const importPath = `../assets/${relative(join(root, 'src', 'assets'), variant.output).replaceAll('\\', '/')}`
      moduleImports.push(`import ${name} from ${JSON.stringify(importPath)};`)
      names[`${variant.format}${variant.width}`] = name
    }
    const [small, large] = group.widths
    entries.push(`${JSON.stringify(key)}:{src:${names[`webp${large}`]},webpSrcSet:\`${'${'}${names[`webp${small}`]}} ${small}w, ${'${'}${names[`webp${large}`]}} ${large}w\`,avifSrcSet:\`${'${'}${names[`avif${small}`]}} ${small}w, ${'${'}${names[`avif${large}`]}} ${large}w\`,widths:[${small},${large}]}`)
  }
  moduleGroups.push(`${group.name}:{${entries.join(',')}}`)
}

await mkdir(join(root, 'src', 'generated'), { recursive: true })
await writeFile(modulePath, `${moduleImports.join('\n')}\n\nexport const responsiveImages={${moduleGroups.join(',')}};\nexport const responsiveImageBySrc=new Map(Object.values(responsiveImages).flatMap(group=>Object.values(group)).map(media=>[media.src,media]));\n`, 'utf8')
console.log(`Optimized storefront imagery written to ${relative(root, outputRoot)}.`)
